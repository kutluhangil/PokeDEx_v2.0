// Memoize path calculations
const pathCache: Record<string, string> = {};

const getSvgPath = (type: string): string => {
  const normalized = type.toLowerCase();
  if (pathCache[normalized]) return pathCache[normalized];

  const grid = PIXEL_ICONS[normalized] || PIXEL_ICONS.normal;
  let path = "";
  grid.forEach((row, r) => {
    for (let c = 0; c < row.length; c++) {
      if (row[c] === "#") {
        path += `M${c},${r}h1v1h-1z `;
      }
    }
  });

  pathCache[normalized] = path;
  return path;
};

interface TypePixelIconProps extends SVGProps<SVGSVGElement> {
  type: string;
  glow?: boolean;
}

export default function TypePixelIcon({ type, glow = true, className, style, ...props }: TypePixelIconProps) {
  const pathData = getSvgPath(type);
  
  return (
    <svg
      viewBox="0 0 12 12"
      className={className}
      style={{
        shapeRendering: "crispEdges",
        display: "inline-block",
        ...style
      }}
      {...props}
    >
      <path
        d={pathData}
        fill="currentColor"
        style={{
          filter: glow ? "drop-shadow(0 0 1px currentColor)" : "none"
        }}
      />
    </svg>
  );
}
